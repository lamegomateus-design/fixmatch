import type { Offer } from "@/types";
import { assets } from "./assets";
import { computeAgioDeagio, computeMatchScore } from "@/lib/finance";

function buildOffer(params: {
  id: string;
  assetId: string;
  sellerId: string;
  sellerType: Offer["sellerType"];
  offeredPU: number;
  offeredRate: number;
  quantity: number;
  urgency: Offer["urgency"];
  status: Offer["status"];
  createdAt: string;
  expiresAt: string;
  reasonForSale?: string;
  notes?: string;
}): Offer {
  const asset = assets.find((a) => a.id === params.assetId)!;
  const volume = params.quantity * params.offeredPU;
  const agioDeagioPct = computeAgioDeagio(asset.currentPU, params.offeredPU);
  const partial: Offer = {
    id: params.id,
    asset,
    sellerId: params.sellerId,
    sellerType: params.sellerType,
    offeredPU: params.offeredPU,
    offeredRate: params.offeredRate,
    quantity: params.quantity,
    volume,
    agioDeagioPct,
    urgency: params.urgency,
    status: params.status,
    createdAt: params.createdAt,
    expiresAt: params.expiresAt,
    matchScore: 0,
    reasonForSale: params.reasonForSale,
    notes: params.notes,
  };
  partial.matchScore = computeMatchScore(partial);
  return partial;
}

